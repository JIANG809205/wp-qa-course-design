def apply(path: str, old: str, new: str) -> str:
    full = os.path.join(ROOT, path)
    text = io.open(full, encoding="utf-8").read()
    if old not in text:
        return f"MISS {path}"
    io.open(full, "w", encoding="utf-8", newline="\n").write(text.replace(old, new, 1))
    return f"OK   {path}"


